import {test,expect} from '@playwright/test'
test('完整 Mock 流程、SSE、刷新恢复、正文、下载和安全渲染',async({page})=>{
 await page.goto('/')
 await expect(page.getByRole('button',{name:'开始研究'})).toBeDisabled()
 await page.getByLabel('输入公司名称或股票代码').fill('示例制造公司')
 await page.getByRole('button',{name:'开始研究'}).click()
 await expect(page.getByText('模拟运行 · 合成数据')).toBeVisible()
 await expect(page.getByRole('list',{name:'最近进度事件'})).toContainText(/resolve_company|research_brief|模拟运行/)
 const id=await page.evaluate(()=>localStorage.getItem('cdr-run'))
 await page.reload()
 await expect(page.getByRole('heading',{name:/公司深度研究报告/})).toBeVisible({timeout:60000})
 expect(await page.evaluate(()=>localStorage.getItem('cdr-run'))).toBe(id)
 const body=page.frameLocator('iframe[title="研究报告正文"]')
 await expect(body.getByRole('heading',{name:'一、公司情况'})).toBeVisible()
 await expect(body.getByRole('navigation',{name:'目录'})).toBeVisible()
 await expect(body.getByRole('heading',{name:/财务增长与盈利能力/})).toBeVisible()
 await expect(body.getByRole('heading',{name:/现金流与利润质量/})).toBeVisible()
 await expect(body.getByRole('heading',{name:'附录：财务报表'})).toBeVisible()
 await expect(body.locator('#F01 figure.fig').first()).toContainText('图1')
 await expect(body.locator('body')).not.toContainText('ev-')
 const [download]=await Promise.all([page.waitForEvent('download'),page.getByRole('link',{name:'下载 DOCX ↓'}).click()])
 expect(download.suggestedFilename()).toMatch(/\.docx$/)
 await download.saveAs('test-results/mock-report.docx')
 await page.screenshot({path:'test-results/completed.png',fullPage:false})
 const run=await page.request.get(`/api/research/${id}`)
 expect((await run.json()).status).toBe('limited')
 const report=await page.request.get(`/api/research/${id}/report`)
 const document=await report.json()
 expect(document.forecasts).toHaveLength(9)
 expect(document.comparisons).toHaveLength(20)
 expect(document.snapshot_id).toBe(document.approved_snapshot_id)
})
test('SSE 断线重连仍完成',async({page,context})=>{
 await page.goto('/');await page.getByLabel('输入公司名称或股票代码').fill('断线恢复公司');await page.getByRole('button',{name:'开始研究'}).click()
 await expect(page.getByText('模拟运行 · 合成数据')).toBeVisible()
 await context.setOffline(true);await page.waitForTimeout(1200);await context.setOffline(false)
 await expect(page.getByRole('heading',{name:/公司深度研究报告/})).toBeVisible({timeout:60000})
 await expect(page.getByText(/报告完成，存在明确限制/)).toBeVisible()
})
test('失败状态与 XSS 安全显示',async({page})=>{
 await page.addInitScript(()=>localStorage.setItem('cdr-run','failed-run'))
 await page.route('**/api/research/failed-run',route=>route.fulfill({json:{run_id:'failed-run',company_input:'<script>alert(1)</script>',mode:'real',status:'failed',stage:'公司识别',error:'未配置模型',limitations:[]}}))
 await page.route('**/api/research/failed-run/events?after=0',route=>route.fulfill({status:200,contentType:'text/event-stream',body:'event: done\ndata: {}\n\n'}))
 await page.goto('/');await expect(page.getByRole('alert')).toContainText('未配置模型')
 await expect(page.getByText(/研究未能完成/)).toBeVisible()
 await expect(page.locator('main')).toContainText('<script>alert(1)</script>')
 expect(await page.locator('main script').count()).toBe(0)
})
