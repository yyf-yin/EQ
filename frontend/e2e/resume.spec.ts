import {test,expect} from '@playwright/test'

test('暂停后刷新保持进度，同一任务继续并完成',async({page})=>{
 await page.goto('/')
 await page.getByLabel('输入公司名称或股票代码').fill('断点续跑验收')
 await page.getByRole('button',{name:'开始研究'}).click()
 await expect(page.getByRole('button',{name:'暂停研究'})).toBeVisible()
 await expect(page.getByRole('button',{name:'继续研究'})).toBeDisabled()
 const id=await page.evaluate(()=>localStorage.getItem('cdr-run'))
 await expect.poll(async()=>{
  const response=await page.request.get(`/api/research/${id}`)
  return (await response.json()).recovery.saved_units.node||0
 },{timeout:30000}).toBeGreaterThan(0)
 await page.getByRole('button',{name:'暂停研究'}).click()
 await expect(page.getByRole('button',{name:'继续研究'})).toBeEnabled({timeout:30000})
 const paused=await (await page.request.get(`/api/research/${id}`)).json()
 expect(paused.status).toBe('interrupted')
 expect(paused.stop_reason).toBe('user')
 await page.screenshot({path:'test-results/resume-paused.png'})
 await page.reload()
 await expect(page.getByRole('button',{name:'继续研究'})).toBeEnabled()
 expect(await page.evaluate(()=>localStorage.getItem('cdr-run'))).toBe(id)
 await page.setViewportSize({width:390,height:844})
 await page.getByRole('button',{name:'调整续跑预算'}).click()
 await expect(page.getByLabel('总调用上限')).toBeVisible()
 await page.screenshot({path:'test-results/resume-mobile.png'})
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true)
 await page.getByRole('button',{name:'继续研究'}).click()
 await expect(page.getByRole('heading',{name:/公司深度研究报告/})).toBeVisible({timeout:60000})
 const final=await (await page.request.get(`/api/research/${id}`)).json()
 expect(final.status).toBe('limited')
 expect(final.resume_count).toBe(1)
 expect(final.recovery.saved_units.node).toBeGreaterThan(paused.recovery.saved_units.node)
 const events=await (await page.request.get(`/api/research/${id}/events`)).text()
 expect((events.match(/"task_name":"resolve_company","status":"completed"/g)||[]).length).toBe(1)
})

test('服务重启后的旧任务保留进度，但不显示暂停或继续入口',async({page})=>{
 await page.goto('/')
 await page.getByLabel('输入公司名称或股票代码').fill('旧程序会话')
 await page.getByRole('button',{name:'开始研究'}).click()
 await page.getByRole('button',{name:'暂停研究'}).click()
 await expect(page.getByRole('button',{name:'继续研究'})).toBeEnabled({timeout:30000})
 const id=await page.evaluate(()=>localStorage.getItem('cdr-run'))
 const saved=await (await page.request.get(`/api/research/${id}`)).json()
 // The real restart/session boundary is covered by backend lifespan tests.
 await page.route(`**/api/research/${id}`,route=>route.fulfill({json:{...saved,recovery:{...saved.recovery,current_session:false,can_pause:false,can_resume:false,can_increase_budget:false,reason:'程序已重启，此任务不能继续；请新建研究，原成果可查看或导出。'}}}))
 await page.reload()
 await expect(page.getByText('程序已重启，此任务不能继续；请新建研究，原成果可查看或导出。')).toBeVisible()
 await expect(page.getByRole('button',{name:'继续研究'})).toHaveCount(0)
 await expect(page.getByRole('button',{name:'暂停研究'})).toHaveCount(0)
 await page.getByLabel('输入公司名称或股票代码').fill('新研究')
 await expect(page.getByRole('button',{name:'开始研究'})).toBeEnabled()
 await page.screenshot({path:'test-results/session-restarted.png'})
})
